import Foundation

enum TutorialMasteryCatalog {
    static func chapters(
        stageTitle: String,
        topicTitle: String,
        tutorialTitle: String,
        language: String
    ) -> [String] {
        entries.enumerated().map { offset, entry in
            markdown(
                number: offset + 41,
                entry: entry,
                stageTitle: stageTitle,
                topicTitle: topicTitle,
                tutorialTitle: tutorialTitle,
                language: language
            )
        }
    }

    private static func markdown(
        number: Int,
        entry: Entry,
        stageTitle: String,
        topicTitle: String,
        tutorialTitle: String,
        language: String
    ) -> String {
        let n = String(format: "%02d", number)

        return #"""
# 深度学习手册 \#(n)：\#(entry.title)

## \#(n).1 核心问题

\#(entry.focus)

把这个问题放回“\#(stageTitle) / \#(topicTitle)”中，它不再是一个孤立术语，而是一套需要被设计、实现、验证和维护的工程能力。学习“\#(tutorialTitle)”时，请先写出你真正要解决的问题，再选择语言、工具和数据结构。工具只是手段，问题定义、约束和验收标准才决定方案是否合适。

## \#(n).2 建立模型

先用输入、状态、转换、输出和失败五个部分描述方案。输入可能来自用户、文件、网络、系统调用或另一个服务；状态必须说明谁拥有、何时改变、是否共享；转换要明确前置条件和后置条件；输出要能被观察和验证；失败则要说明如何恢复。

如果无法画出模型，先不要写大量代码。用纸笔列出对象、关系、生命周期和资源上限，再标出不可逆操作。对 `\#(language)` 相关实现，还要确认类型、内存、错误传播和并发边界。模型越清楚，后面调试和重构的成本越低。

## \#(n).3 分步实验

1. 准备一个最小、可重复的输入，记录版本、环境和预期输出。
2. 只实现核心路径，不加入缓存、并发或界面等额外复杂度。
3. 运行并保存标准输出、错误输出、退出码和关键状态。
4. 应用一次本节的实践任务：\#(entry.practice)
5. 制造一个可控错误，确认错误可定位、可恢复，并补充回归检查。
6. 将实验整理成脚本或 README，确保另一位学习者可以复现。

实验时一次只改变一个变量。不要同时更换数据规模、配置、依赖和运行环境，否则无法判断差异来自哪里。至少要覆盖空输入、正常输入、边界输入和资源不足。

## \#(n).4 证据与验证

验证不能只依赖“看起来正常”。功能上要检查输出和不变量；性能上要记录时间、吞吐、延迟分位数和资源峰值；安全上要检查输入、权限、敏感信息和错误信息；可维护性上要检查测试、文档、日志和回滚方案。

把证据分成事实、推断和待验证事项。事实是命令输出和测量结果；推断是你对原因的解释；待验证事项需要下一轮实验。三者混在一起，会导致错误结论被当成确定性知识。

## \#(n).5 常见风险

本节最需要警惕的是：\#(entry.risk)

风险不仅包括程序崩溃，还包括悄悄给出错误结果、资源持续泄漏、数据无法恢复、权限过大、日志泄露、升级不兼容和长期维护困难。为每个风险写出触发条件、影响范围、检测方式和缓解措施。

如果风险无法完全消除，就把它显式记录为已知限制，并设计监控或回滚。不要用“正常情况下不会发生”代替风险分析。生产环境真正考验的是异常、边界和部分失败。

## \#(n).6 工程迁移

将本节方法与实际情况连接：\#(entry.connection)

把方案拆成最小可行版本、工程化版本和生产版本。最小版本证明模型；工程化版本补齐配置、测试、日志和错误处理；生产版本增加权限、监控、容量、迁移和恢复。不要一开始就实现所有层，但必须知道每一层解决什么问题。

如果需要团队协作，接口和文档应与代码一起维护。每次修改都记录动机、影响、测试和回滚方式。让下一位维护者能够理解设计，而不是只看到最终代码。

## \#(n).7 掌握挑战

挑战一：用不超过 300 字解释本节，并给出一个反例。

挑战二：从空目录建立一个可运行示例，再故意制造一次失败并修复。

挑战三：写出性能、安全和可维护性各一项检查，并实际执行。

挑战四：把本节方法迁移到另一个相关主题，说明哪些约束发生变化。

完成标准不是背出结论，而是能够独立定义问题、选择方案、收集证据、说明取舍，并把过程交给别人复现。
"""#
    }

